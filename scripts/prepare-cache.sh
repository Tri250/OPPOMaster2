#!/bin/bash
# CI 构建脚本 - 在有网络的环境中预缓存依赖
# 用于沙箱环境离线构建

set -e

echo "=========================================="
echo "步骤 1: 下载 Gradle Wrapper"
echo "=========================================="
./gradlew --version

echo ""
echo "=========================================="
echo "步骤 2: 下载项目依赖"
echo "=========================================="
./gradlew dependencies --no-daemon

echo ""
echo "=========================================="
echo "步骤 3: 验证构建"
echo "=========================================="
./gradlew assembleDebug --no-daemon

echo ""
echo "=========================================="
echo "缓存已准备完成"
echo "=========================================="
echo ""
echo "现在可以在沙箱环境中使用以下命令进行离线构建："
echo "  gradle assembleDebug --offline"
echo ""